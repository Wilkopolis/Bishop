"""Generate src/components/projectIconData.ts from the icon catalog in the Rook repo.

Usage: python scripts/gen-project-icons.py [path to Rook]

Rook is the sibling repo by default. Only icons in Rook's catalog are copied.
Icons are Phosphor duotone (MIT) and Kenney chess pieces (CC0).
"""
import re
import sys
from pathlib import Path

repo = Path(__file__).resolve().parent.parent
rook = Path(sys.argv[1]) if len(sys.argv) > 1 else repo.parent / 'Rook'
out = repo / 'src' / 'components' / 'projectIconData.ts'

catalog_ts = (rook / 'src' / 'components' / 'iconCatalog.ts').read_text(encoding='utf-8')
data_ts = (rook / 'src' / 'components' / 'phosphorIconsData.ts').read_text(encoding='utf-8')

categories = re.findall(r"\{ id: '([^']+)', label: '([^']+)', icon: '[^']+' \}", catalog_ts)
items = re.findall(r"\{ id: '([^']+)', label: '([^']+)', category: '([^']+)' \}", catalog_ts)
svg = dict(re.findall(r"^  '([^']+)': '(.*)',$", data_ts, re.M))

missing = [i for i, _, _ in items if i not in svg]
if missing:
    sys.exit(f'No artwork for: {", ".join(missing)}')

lines = [
    '// Generated by scripts/gen-project-icons.py from the Rook repo. Do not edit by hand.',
    '// Phosphor Icons (MIT, see LICENSE-phosphor.txt) and Kenney chess pieces (CC0, see src/assets).',
    '',
    'export const PROJECT_ICON_CATEGORIES = [',
]
lines += [f"  {{ id: '{i}', label: '{label}' }}," for i, label in categories]
lines += ['];', '', 'export const PROJECT_ICONS = [']
lines += [f"  {{ id: '{i}', label: '{label}', category: '{cat}' }}," for i, label, cat in items]
lines += ['];', '', 'export const PROJECT_ICON_SVG: Record<string, string> = {']
lines += [f"  '{i}': '{svg[i]}'," for i, _, _ in items]
lines += ['};', '']

out.write_text('\n'.join(lines), encoding='utf-8')
print(f'Wrote {len(items)} icons to {out}')
