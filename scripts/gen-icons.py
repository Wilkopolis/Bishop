def duotone_or_own(name, weight):
    f = root / 'SVGs' / 'duotone' / f'{name}-duotone.svg'
    if not f.exists():
        suffix = '' if weight == 'regular' else f'-{weight}'
        f = root / 'SVGs' / weight / f'{name}{suffix}.svg'
    svg = f.read_text(encoding='utf-8')
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    return re.sub(r'<rect width="256" height="256" fill="none"\s*/>', '', inner).strip()

