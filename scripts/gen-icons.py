"""Generate src/components/icons.tsx from the local Phosphor icon set.

Usage: python scripts/gen-icons.py "D:/Game Tools and Assets/icons/phosphor"

Only the icons listed in ICONS are inlined. Edit the list and re-run to add more.
"""
import re
import shutil
import sys
from pathlib import Path

# Component name -> (phosphor icon name, weight)
ICONS = {
    'Check': ('check', 'bold'),
    'ChevronRight': ('caret-right', 'bold'),
    'Copy': ('copy-simple', 'bold'),
    'Download': ('download-simple', 'bold'),
    'FileAudio': ('file-audio', 'bold'),
    'FileText': ('file-text', 'bold'),
    'Folder': ('folder', 'bold'),
    'FolderOpen': ('folder-open', 'bold'),
    'FolderPlus': ('folder-plus', 'bold'),
    'GripVertical': ('dots-six-vertical', 'bold'),
    'ImageIcon': ('image', 'bold'),
    'Loader2': ('spinner-gap', 'bold'),
    'Mic': ('microphone', 'bold'),
    'Minus': ('minus', 'bold'),
    'MoreHorizontal': ('dots-three', 'bold'),
    'NotebookText': ('notebook', 'bold'),
    'Plus': ('plus', 'bold'),
    'Search': ('magnifying-glass', 'bold'),
    'Settings': ('gear-six', 'bold'),
    'Sparkles': ('sparkle', 'bold'),
    'Square': ('square', 'bold'),
    'Stop': ('stop', 'fill'),
    'Trash2': ('trash', 'bold'),
    'UploadSimple': ('upload-simple', 'bold'),
    'WarningCircle': ('warning-circle', 'bold'),
    'TerminalWindow': ('terminal-window', 'bold'),
    'ArrowClockwise': ('arrow-clockwise', 'bold'),
    'CaretDown': ('caret-down', 'bold'),
    'ArrowRight': ('arrow-right', 'bold'),
    'X': ('x', 'bold'),
}

root = Path(sys.argv[1])
repo = Path(__file__).resolve().parent.parent
out = repo / 'src' / 'components' / 'icons.tsx'

entries = []
for comp, (name, weight) in ICONS.items():
    svg = (root / 'SVGs' / weight / f'{name}-{weight}.svg').read_text(encoding='utf-8')
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    inner = re.sub(r'<rect width="256" height="256" fill="none"\s*/>', '', inner).strip()
    entries.append(f"export const {comp} = icon({inner!r});".replace("\\'", "'"))

out.write_text(
    """// Generated by scripts/gen-icons.py from Phosphor Icons (MIT, see LICENSE-phosphor.txt). Do not edit by hand.
import type { CSSProperties } from 'react';

export interface IconProps {
  size?: number;
  className?: string;
  style?: CSSProperties;
  title?: string;
}

function icon(markup: string) {
  return function Icon({ size = 16, className, style, title }: IconProps) {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 256 256"
        width={size}
        height={size}
        fill="currentColor"
        className={className}
        style={style}
        role={title ? 'img' : undefined}
        aria-hidden={title ? undefined : true}
        aria-label={title}
        dangerouslySetInnerHTML={{ __html: markup }}
      />
    );
  };
}

"""
    + '\n'.join(entries)
    + '\n',
    encoding='utf-8',
)
shutil.copyfile(root / 'LICENSE', repo / 'src' / 'components' / 'LICENSE-phosphor.txt')
print(f'wrote {out} ({len(entries)} icons)')
